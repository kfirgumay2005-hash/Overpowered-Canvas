import esbuild from "esbuild";
import { readFile } from "node:fs/promises";
import { builtinModules, createRequire } from "node:module";
import { deflateRawSync } from "node:zlib";
import { emojiDataPlugin } from "./scripts/emoji-data.mjs";

const require = createRequire(import.meta.url);

/**
 * `import source from "elk-worker-source"` → the elkjs worker script, deflate-raw compressed and
 * base64 encoded (unpacked and run as a Blob worker on first use).
 *
 * Not plain text: Windows Defender analyzes a 1.5 MB script found inside a string as code the
 * first time it sees main.js (after every reboot), which took ~1.7 s of Obsidian's start-up and
 * made Obsidian report the plugin as slow to load. Packed, the whole file scans in ~0.3 s.
 * Compressed rather than only encoded so main.js stays under 5 MB.
 */
const elkWorkerText = {
	name: "elk-worker-source",
	setup(build) {
		build.onResolve({ filter: /^elk-worker-source$/ }, () => ({ path: require.resolve("elkjs/lib/elk-worker.min.js"), namespace: "elk-text" }));
		build.onLoad({ filter: /.*/, namespace: "elk-text" }, async (args) => ({ contents: `export default ${JSON.stringify(deflateRawSync(await readFile(args.path), { level: 9 }).toString("base64"))};`, loader: "js" }));
	},
};

const production = process.argv[2] === "production";

const banner = "/* Overpowered Canvas — generated by esbuild, edit the sources in src/ instead. */";

/** Obsidian provides these at runtime; never bundle them. */
const external = [
	"obsidian",
	"electron",
	"@codemirror/autocomplete",
	"@codemirror/collab",
	"@codemirror/commands",
	"@codemirror/language",
	"@codemirror/lint",
	"@codemirror/search",
	"@codemirror/state",
	"@codemirror/view",
	"@lezer/common",
	"@lezer/highlight",
	"@lezer/lr",
	...builtinModules,
	...builtinModules.map((m) => `node:${m}`),
];

const jsContext = await esbuild.context({
	banner: { js: banner },
	entryPoints: ["src/main.ts"],
	bundle: true,
	plugins: [elkWorkerText, emojiDataPlugin],
	external,
	format: "cjs",
	target: "es2022",
	logLevel: "info",
	sourcemap: production ? false : "inline",
	treeShaking: true,
	minify: production,
	// Translations and emoji names as real UTF-8: by default each non-Latin character is written
	// as an escape (6 bytes instead of 2–3), which made main.js over a megabyte larger.
	charset: "utf8",
	outfile: "main.js",
});

// Every module's styles.css is @imported from src/styles.css and bundled into one file.
const cssContext = await esbuild.context({
	banner: { css: banner },
	entryPoints: ["src/styles.css"],
	bundle: true,
	logLevel: "info",
	minify: production,
	outfile: "styles.css",
});

const contexts = [jsContext, cssContext];
if (production) {
	await Promise.all(contexts.map((c) => c.rebuild()));
	process.exit(0);
} else {
	await Promise.all(contexts.map((c) => c.watch()));
}
