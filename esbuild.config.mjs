import esbuild from "esbuild";
import { builtinModules } from "node:module";

const production = process.argv[2] === "production";

const banner = "/* Overpowered Canvas — generated by esbuild, edit the sources in src/ instead. */";

/** Obsidian provides these at runtime; never bundle them. */
const external = [
	"obsidian",
	"electron",
	"@codemirror/autocomplete",
	"@codemirror/collab",
	"@codemirror/commands",
	"@codemirror/language",
	"@codemirror/lint",
	"@codemirror/search",
	"@codemirror/state",
	"@codemirror/view",
	"@lezer/common",
	"@lezer/highlight",
	"@lezer/lr",
	...builtinModules,
	...builtinModules.map((m) => `node:${m}`),
];

const jsContext = await esbuild.context({
	banner: { js: banner },
	entryPoints: ["src/main.ts"],
	bundle: true,
	external,
	format: "cjs",
	target: "es2022",
	logLevel: "info",
	sourcemap: production ? false : "inline",
	treeShaking: true,
	minify: production,
	outfile: "main.js",
});

// Every module's styles.css is @imported from src/styles.css and bundled into one file.
const cssContext = await esbuild.context({
	banner: { css: banner },
	entryPoints: ["src/styles.css"],
	bundle: true,
	logLevel: "info",
	minify: production,
	outfile: "styles.css",
});

// Paste-into-console probe of the canvas internals (see docs/INTERNALS.md). Not part of the plugin.
const probeContext = await esbuild.context({
	banner: { js: "/* Overpowered Canvas — canvas internals probe. Paste into Obsidian's developer console with a canvas open. Generated from src/internals/probe.ts. */" },
	entryPoints: ["src/internals/probe-console.ts"],
	bundle: true,
	format: "iife",
	target: "es2022",
	logLevel: "info",
	outfile: "scripts/console/probe-internals.js",
});

const contexts = [jsContext, cssContext, probeContext];
if (production) {
	await Promise.all(contexts.map((c) => c.rebuild()));
	process.exit(0);
} else {
	await Promise.all(contexts.map((c) => c.watch()));
}
