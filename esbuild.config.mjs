import esbuild from "esbuild";
import { readFile } from "node:fs/promises";
import { builtinModules, createRequire } from "node:module";

const require = createRequire(import.meta.url);

/** `import source from "elk-worker-source"` → the elkjs worker script as a string (run as a Blob worker). */
const elkWorkerText = {
	name: "elk-worker-source",
	setup(build) {
		build.onResolve({ filter: /^elk-worker-source$/ }, () => ({ path: require.resolve("elkjs/lib/elk-worker.min.js"), namespace: "elk-text" }));
		build.onLoad({ filter: /.*/, namespace: "elk-text" }, async (args) => ({ contents: await readFile(args.path, "utf8"), loader: "text" }));
	},
};

const production = process.argv[2] === "production";

const banner = "/* Overpowered Canvas — generated by esbuild, edit the sources in src/ instead. */";

/** Obsidian provides these at runtime; never bundle them. */
const external = [
	"obsidian",
	"electron",
	"@codemirror/autocomplete",
	"@codemirror/collab",
	"@codemirror/commands",
	"@codemirror/language",
	"@codemirror/lint",
	"@codemirror/search",
	"@codemirror/state",
	"@codemirror/view",
	"@lezer/common",
	"@lezer/highlight",
	"@lezer/lr",
	...builtinModules,
	...builtinModules.map((m) => `node:${m}`),
];

const jsContext = await esbuild.context({
	banner: { js: banner },
	entryPoints: ["src/main.ts"],
	bundle: true,
	plugins: [elkWorkerText],
	external,
	format: "cjs",
	target: "es2022",
	logLevel: "info",
	sourcemap: production ? false : "inline",
	treeShaking: true,
	minify: production,
	outfile: "main.js",
});

// Every module's styles.css is @imported from src/styles.css and bundled into one file.
const cssContext = await esbuild.context({
	banner: { css: banner },
	entryPoints: ["src/styles.css"],
	bundle: true,
	logLevel: "info",
	minify: production,
	outfile: "styles.css",
});

const contexts = [jsContext, cssContext];
if (production) {
	await Promise.all(contexts.map((c) => c.rebuild()));
	process.exit(0);
} else {
	await Promise.all(contexts.map((c) => c.watch()));
}
